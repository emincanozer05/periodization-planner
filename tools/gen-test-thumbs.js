/* Writes src/app/045-test-thumbs.jsx: the small grey-scale test pictures (tests/sm/, fms/sm/)
   carried inside the page as data URLs, keyed by the full-size picture's path in TEST_IMG.
   The printed sheets use them, so a picture never depends on a fetch from the site (a host
   serving from a sub-folder, a weak connection, the print dialog opening early).
   Run after changing a picture in tests/ or fms/ (and its copy in sm/):
     node tools/gen-test-thumbs.js            write the part
     node tools/gen-test-thumbs.js --check    exit 1 if the part is out of date */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'src/app/045-test-thumbs.jsx');
const rows = [];
for (const dir of ['tests', 'fms']) {
  const sm = path.join(ROOT, dir, 'sm');
  for (const f of fs.readdirSync(sm).filter(f => f.endsWith('.jpg')).sort()) {
    rows.push(`  '${dir}/${f}':'data:image/jpeg;base64,${fs.readFileSync(path.join(sm, f)).toString('base64')}',`);
  }
}
const text = `/* TEST THUMBNAILS — generated by tools/gen-test-thumbs.js, do not edit by hand.
   The grey-scale copies of the test pictures (tests/sm/, fms/sm/) as data URLs, keyed by the
   full-size path TEST_IMG names. The Athlete Information sheet prints from these, so its
   pictures need no fetch from the site. */
const TEST_THUMB={
${rows.join('\n')}
};
`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('045-test-thumbs.jsx güncel değil: node tools/gen-test-thumbs.js'); process.exit(1); }
  console.log('045-test-thumbs.jsx güncel');
} else {
  fs.writeFileSync(OUT, text);
  console.log(`045-test-thumbs.jsx yazıldı (${rows.length} görsel, ${Math.round(text.length / 1024)} KB)`);
}
